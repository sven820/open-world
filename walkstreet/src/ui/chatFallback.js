let fallbackCursor = 0;

/** 本地兜底回复：关键词命中规则表，否则轮换通用引导语 */
export function localReply(text) {
  const q = sanitize(text).toLowerCase();
  if (!q) return "想聊点什么？直接打字发给我就好～";
  for (const rule of RULES) {
    if (rule.keys.some((k) => q.includes(k))) return rule.reply;
  }
  const reply = FALLBACK_REPLIES[fallbackCursor % FALLBACK_REPLIES.length];
  fallbackCursor += 1;
  return reply;
}
